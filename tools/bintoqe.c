#include <stdio.h>

int main(int argc, char **argv)
{
    FILE *f;
    int c, column = 0;

    if (argc != 3) {
        fprintf(stderr, "usage: bintoqe file symbol > output.h\n");
        return 1;
    }
    f = fopen(argv[1], "rb");
    if (!f) {
        perror(argv[1]);
        return 1;
    }
    printf("/* Automatically generated by bintoqe. */\n");
    printf("static const unsigned char %s[] = {\n", argv[2]);
    while ((c = fgetc(f)) != EOF) {
        if (column == 0)
            printf("   ");
        printf(" 0x%02x,", c);
        if (++column == 12) {
            putchar('\n');
            column = 0;
        }
    }
    if (ferror(f)) {
        perror(argv[1]);
        fclose(f);
        return 1;
    }
    fclose(f);
    if (column)
        putchar('\n');
    printf("};\n");
    return fflush(stdout) == EOF ? 1 : 0;
}
